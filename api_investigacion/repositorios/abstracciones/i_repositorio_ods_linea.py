"""El protocolo mantiene el acceso a datos intercambiable para la capa de negocio."""

from typing import Protocol


class IRepositorioOdsLinea(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, linea_investigacion: int, ods: int) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def eliminar_logico(self, linea_investigacion: int, ods: int) -> int: ...
