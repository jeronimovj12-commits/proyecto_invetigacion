"""Interfaz específica para que el servicio de áreas no dependa de SQL ni de PostgreSQL."""

from typing import Protocol


class IRepositorioAreaConocimiento(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_id(self, identificador: str) -> dict | None: ...
    async def crear(self, datos: dict) -> str | None: ...
    async def actualizar(self, identificador: str, datos: dict) -> int: ...
    async def eliminar_logico(self, identificador: str) -> int: ...
