"""El servicio depende de este contrato y no de la conexión PostgreSQL."""

from typing import Protocol


class IRepositorioGrupoLinea(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, grupo_investigacion: int, linea_investigacion: int) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def eliminar_logico(self, grupo_investigacion: int, linea_investigacion: int) -> int: ...
