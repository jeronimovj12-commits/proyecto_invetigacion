"""Contrato de persistencia de participación en semilleros con clave compuesta explícita."""

from typing import Protocol


class IRepositorioParticipaSemillero(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, docente: int, semillero: int) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def actualizar_por_claves(self, docente: int, semillero: int, datos: dict) -> int: ...
    async def eliminar_logico(self, docente: int, semillero: int) -> int: ...
