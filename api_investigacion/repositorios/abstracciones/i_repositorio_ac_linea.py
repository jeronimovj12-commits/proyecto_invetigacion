"""El segundo componente textual evita convertir el código de área en entero."""

from typing import Protocol


class IRepositorioAcLinea(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, linea_investigacion: int, area_conocimiento: str) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def eliminar_logico(self, linea_investigacion: int, area_conocimiento: str) -> int: ...
