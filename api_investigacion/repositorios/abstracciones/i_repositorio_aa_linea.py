"""La interfaz aísla las reglas de vínculo de los detalles del motor SQL."""

from typing import Protocol


class IRepositorioAaLinea(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, area_aplicacion: int, linea_investigacion: int) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def eliminar_logico(self, area_aplicacion: int, linea_investigacion: int) -> int: ...
