"""El contrato permite sustituir PostgreSQL por un repositorio falso en pruebas."""

from typing import Protocol


class IRepositorioSemilleroLinea(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, semillero: int, linea_investigacion: int) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def eliminar_logico(self, semillero: int, linea_investigacion: int) -> int: ...
