"""Contrato de persistencia de participación en grupos con operaciones sobre su clave compuesta."""

from typing import Protocol


class IRepositorioParticipaGrupo(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_claves(self, docente_cedula: int, grupo_investigacion_id: int) -> dict | None: ...
    async def crear(self, datos: dict) -> None: ...
    async def actualizar_por_claves(self, docente_cedula: int, grupo_investigacion_id: int, datos: dict) -> int: ...
    async def eliminar_logico(self, docente_cedula: int, grupo_investigacion_id: int) -> int: ...
