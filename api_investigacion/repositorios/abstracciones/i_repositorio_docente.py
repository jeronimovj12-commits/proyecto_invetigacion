"""Contrato de persistencia docente para desacoplar el negocio de PostgreSQL."""

from typing import Protocol


class IRepositorioDocente(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_id(self, cedula: int) -> dict | None: ...
    async def crear(self, datos: dict) -> int | None: ...
    async def actualizar(self, cedula: int, datos: dict) -> int: ...
    async def eliminar_logico(self, cedula: int) -> int: ...
