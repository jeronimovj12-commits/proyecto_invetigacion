"""Interfaz de persistencia de universidades para mantener el servicio independiente del motor."""

from typing import Protocol


class IRepositorioUniversidad(Protocol):
    async def obtener_todos(self, limite: int) -> list[dict]: ...
    async def obtener_por_id(self, identificador: int) -> dict | None: ...
    async def crear(self, datos: dict) -> int | None: ...
    async def actualizar(self, identificador: int, datos: dict) -> int: ...
    async def eliminar_logico(self, identificador: int) -> int: ...
