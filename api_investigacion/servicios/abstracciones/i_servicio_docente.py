"""Interfaz docente para que el controlador no dependa de la clase de negocio concreta."""

from typing import Protocol


class IServicioDocente(Protocol):
    async def listar(self, limite: int) -> list[dict]: ...
    async def obtener(self, cedula: int) -> dict: ...
    async def crear(self, datos: dict) -> int | None: ...
    async def actualizar(self, cedula: int, datos: dict) -> int: ...
    async def eliminar(self, cedula: int) -> int: ...
