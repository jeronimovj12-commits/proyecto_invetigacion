"""Interfaz de negocio de términos clave sin dependencia del adaptador PostgreSQL."""

from typing import Protocol


class IServicioTerminoClave(Protocol):
    async def listar(self, limite: int) -> list[dict]: ...
    async def obtener(self, identificador: str) -> dict: ...
    async def crear(self, datos: dict) -> str | int | None: ...
    async def actualizar(self, identificador: str, datos: dict) -> int: ...
    async def eliminar(self, identificador: str) -> int: ...
