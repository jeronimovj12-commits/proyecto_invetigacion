"""Interfaz de negocio de líneas para ocultar el motor y facilitar dobles de prueba."""

from typing import Protocol


class IServicioLineaInvestigacion(Protocol):
    async def listar(self, limite: int) -> list[dict]: ...
    async def obtener(self, identificador: int) -> dict: ...
    async def crear(self, datos: dict) -> str | int | None: ...
    async def actualizar(self, identificador: int, datos: dict) -> int: ...
    async def eliminar(self, identificador: int) -> int: ...
